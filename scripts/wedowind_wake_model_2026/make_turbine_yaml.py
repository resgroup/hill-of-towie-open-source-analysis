"""Generate the public FLORIS turbine definition for the Hill of Towie SWT-2.3-82 turbines.

The power and thrust curves come from PyWake's ``GenericWindTurbine`` with every argument except the
name, diameter, hub height and rated power at its PyWake default; those four come from the Zenodo
turbine metadata. No manufacturer curve is used.

PyWake is not a project dependency. To regenerate the committed yaml, install it ad hoc first::

    uv sync --group wedowind
    uv pip install py_wake
    uv run python -m scripts.wedowind_wake_model_2026.make_turbine_yaml
"""

import logging
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import py_wake
import yaml
from floris.turbine_library.turbine_utilities import build_cosine_loss_turbine_dict
from py_wake.wind_turbines.generic_wind_turbines import GenericWindTurbine

from hot_open.settings import get_data_dir, get_out_dir
from hot_open.sourcing_data import ensure_hot_data_files
from scripts.logger import setup_logger

logger = logging.getLogger(__name__)

TURBINE_NAME = "SWT-2.3-82"
FLORIS_INPUTS_DIR = Path(__file__).parent / "floris_inputs"
TURBINE_YAML_PATH = FLORIS_INPUTS_DIR / "swt_2_3_82_generic.yaml"
WIND_SPEEDS = np.round(np.arange(0.0, 30.0 + 0.25, 0.25), 2)


def read_turbine_dimensions() -> dict[str, float]:
    metadata_fname = "Hill_of_Towie_turbine_metadata.csv"
    ensure_hot_data_files([metadata_fname], data_dir=get_data_dir())
    md = pd.read_csv(get_data_dir() / metadata_fname)
    dims = {}
    for key, col in [
        ("diameter", "Rotor Diameter (m)"),
        ("hub_height", "Hub Height (m)"),
        ("power_norm", "Rated power (kW)"),
    ]:
        values = md[col].unique()
        if len(values) != 1:
            msg = f"expected one value of {col} across the farm, got {values}"
            raise ValueError(msg)
        dims[key] = float(values[0])
    return dims


def make_turbine_dict(dims: dict[str, float]) -> dict:
    wt = GenericWindTurbine(name=TURBINE_NAME, **dims)
    turbine_data = {
        "wind_speed": WIND_SPEEDS.tolist(),
        "power": np.round(wt.power(WIND_SPEEDS) / 1000, 3).tolist(),  # W -> kW
        "thrust_coefficient": np.round(wt.ct(WIND_SPEEDS), 5).tolist(),
    }
    return build_cosine_loss_turbine_dict(
        turbine_data,
        TURBINE_NAME,
        hub_height=dims["hub_height"],
        rotor_diameter=dims["diameter"],
    )


def write_turbine_yaml(turbine_dict: dict, *, dims: dict[str, float], out_path: Path) -> None:
    args_str = ", ".join(f"{k}={v:g}" for k, v in dims.items())
    header = (
        f"# Generated by scripts/wedowind_wake_model_2026/{Path(__file__).name}; do not edit by hand.\n"
        f"# Curves from py_wake {py_wake.__version__} "
        f'GenericWindTurbine(name="{TURBINE_NAME}", {args_str}), other arguments at PyWake defaults.\n'
        "# Converted with floris build_cosine_loss_turbine_dict, cosine-loss exponents at FLORIS defaults.\n"
    )
    logger.info("Writing: %s", out_path)
    out_path.write_text(header + yaml.safe_dump(turbine_dict, sort_keys=False), encoding="utf-8")


def plot_curves(turbine_dict: dict, *, out_dir: Path) -> None:
    table = turbine_dict["power_thrust_table"]
    fig, ax_p = plt.subplots(figsize=(8, 5))
    ax_ct = ax_p.twinx()
    ax_p.plot(table["wind_speed"], table["power"], color="tab:blue", label="power")
    ax_ct.plot(table["wind_speed"], table["thrust_coefficient"], color="tab:orange", label="Ct")
    ax_p.set_xlabel("wind speed [m/s]")
    ax_p.set_ylabel("power [kW]")
    ax_ct.set_ylabel("Ct [-]")
    ax_p.grid(visible=True, alpha=0.3)
    fig.legend(loc="center right", bbox_to_anchor=(0.88, 0.5))
    ax_p.set_title(f"{TURBINE_NAME} generic curves (PyWake GenericWindTurbine)")
    plot_path = out_dir / "swt_2_3_82_generic_curves.png"
    logger.info("Writing: %s", plot_path)
    fig.savefig(plot_path, dpi=150, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    out_dir = get_out_dir(dir_name=Path(__file__).stem)
    setup_logger(out_dir / f"{Path(__file__).stem}.log")

    dims = read_turbine_dimensions()
    turbine_dict = make_turbine_dict(dims)
    write_turbine_yaml(turbine_dict, dims=dims, out_path=TURBINE_YAML_PATH)
    plot_curves(turbine_dict, out_dir=out_dir)
